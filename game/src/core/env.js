/* [규칙] 규칙 계산이 바깥 세상과 만나는 유일한 통로 (포트·어댑터 방식)
   - PRES: "화면에 이렇게 보여 주세요" 알림 창구. 규칙은 결과만 알리고, 실제 그리기는 render 가 여기에 연결(어댑터)해서 처리.
     화면이 없는 서버·테스트에서는 아무것도 안 하는 기본값 그대로 씀 → 같은 규칙 코드가 어디서나 돎.
       path(유닛키, 칸 목록)  걷는 애니메이션        fx(종류, x, y, 지연)  스킬 이펙트
       trim(유닛키, n)       예약된 걸음 n칸 취소     snap(유닛키, x, y)    순간이동처럼 위치만 바꿈
       kick()               애니메이션 시작         fallDelay(유닛키)     구덩이 낙하 연출 시작까지 시간(ms)
   - NOW(): 연출용 시각(애니메이션 타이밍 기록). 규칙 판단에는 쓰지 않음. 서버·테스트는 바꿔 끼울 수 있음.
   - RAND(): 규칙이 쓰는 무작위(0 이상 1 미만). 규칙은 Math.random 을 직접 쓰지 않고 반드시 이것만 씀.
     씨앗을 정한 의사난수(mulberry32)이고 진행 값이 게임 상태 S.rng 안에 있음 → 같은 씨앗·같은 행동이면 어디서나 같은 결과.
   - ARAND(): 컴퓨터(AI) 전용 무작위(진행 값 S.airng). AI 는 "플레이어"라서 판단용 주사위를 규칙과 따로 씀
     → 판의 결과는 기록된 행동만으로 정해짐(리플레이할 때 AI 를 다시 돌릴 필요 없음).
   - SEED(): 새 판의 씨앗. 브라우저에선 무작위로 정하고, 서버는 자기가 정한 값을 넣으면 됨. */
const PRES = { path() {}, fx() {}, trim() {}, snap() {}, kick() {}, fallDelay() { return 200; } };
let NOW = () => Date.now();
let SEED = () => (Math.random() * 4294967296) >>> 0;
function mulberry(k) {
  let t = (S[k] = (S[k] + 0x6D2B79F5) | 0);
  t = Math.imul(t ^ (t >>> 15), t | 1);
  t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
}
const RAND = () => mulberry("rng"), ARAND = () => mulberry("airng");
